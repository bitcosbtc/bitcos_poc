import asyncio
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Dict, Any, Optional, List
from datetime import datetime
import requests
from ..config import settings


class NotificationService:
    def __init__(self):
        self.alert_history: List[Dict[str, Any]] = []
        self.max_history = 100

    def _log_alert(self, alert: Dict[str, Any]):
        self.alert_history.insert(0, alert)
        if len(self.alert_history) > self.max_history:
            self.alert_history.pop()

    def get_recent_alerts(self, limit: int = 30) -> List[Dict[str, Any]]:
        return self.alert_history[:limit]

    # --- EMAIL DISPATCHER ---
    def _send_email_sync(
        self,
        subject: str,
        body_text: str,
        body_html: Optional[str] = None,
        recipient: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Synchronous email sending to be executed inside asyncio.to_thread worker.
        """
        user = settings.EMAIL_HOST_USER
        password = settings.EMAIL_HOST_PASSWORD
        host = settings.EMAIL_HOST or "smtp-mail.outlook.com"
        port = settings.EMAIL_PORT or 587
        use_tls = settings.EMAIL_USE_TLS
        to_email = recipient or settings.ALERT_RECIPIENT_EMAIL or user

        if not user or not password:
            return {"success": False, "error": "Email credentials not configured in settings"}

        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = f"[BITCOS AI BOT] {subject}"
            msg["From"] = user
            msg["To"] = to_email

            # Attach plain text
            msg.attach(MIMEText(body_text, "plain"))

            # Attach HTML if provided
            if body_html:
                msg.attach(MIMEText(body_html, "html"))
            else:
                html_default = f"""
                <div style="font-family: Arial, sans-serif; padding: 20px; background-color: #f4f6f8; color: #1a202c;">
                    <div style="max-width: 600px; margin: auto; background: white; border-radius: 8px; border: 1px solid #e2e8f0; overflow: hidden;">
                        <div style="background-color: #001233; color: white; padding: 16px 20px;">
                            <h2 style="margin: 0; font-size: 18px;">Bitcos AI Trading & Risk Alert</h2>
                        </div>
                        <div style="padding: 20px;">
                            <h3 style="color: #2b6cb0; margin-top: 0;">{subject}</h3>
                            <pre style="white-space: pre-wrap; font-family: monospace; background: #edf2f7; padding: 12px; border-radius: 6px; font-size: 13px;">{body_text}</pre>
                            <p style="font-size: 11px; color: #718096; margin-top: 20px; border-top: 1px solid #e2e8f0; padding-top: 10px;">
                                Generated by Bitcos Quant & AI Advisory Watchdog Engine.
                            </p>
                        </div>
                    </div>
                </div>
                """
                msg.attach(MIMEText(html_default, "html"))

            server = smtplib.SMTP(host, port, timeout=12)
            if use_tls:
                server.starttls()
            server.login(user, password)
            server.sendmail(user, [to_email], msg.as_string())
            server.quit()
            return {"success": True, "recipient": to_email}
        except Exception as e:
            return {"success": False, "error": str(e)}

    async def send_email(
        self,
        subject: str,
        body_text: str,
        body_html: Optional[str] = None,
        recipient: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Async wrapper for non-blocking email delivery.
        """
        return await asyncio.to_thread(
            self._send_email_sync,
            subject,
            body_text,
            body_html,
            recipient
        )

    # --- TELEGRAM DISPATCHER ---
    def _send_telegram_sync(self, message: str, token: str, cid: str) -> Dict[str, Any]:
        url = f"https://api.telegram.org/bot{token}/sendMessage"
        payload = {
            "chat_id": cid,
            "text": message,
            "parse_mode": "HTML",
            "disable_web_page_preview": True
        }
        try:
            res = requests.post(url, json=payload, timeout=10)
            data = res.json()
            if data.get("ok"):
                return {"success": True, "message_id": data.get("result", {}).get("message_id")}
            else:
                return {"success": False, "error": data.get("description", "Telegram API returned not ok")}
        except Exception as e:
            return {"success": False, "error": str(e)}

    async def send_telegram(
        self,
        message: str,
        bot_token: Optional[str] = None,
        chat_id: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Sends an instant high-priority mobile push notification via Telegram Bot API.
        """
        token = bot_token or settings.TELEGRAM_BOT_TOKEN
        cid = chat_id or settings.TELEGRAM_CHAT_ID

        if not token or not cid:
            return {
                "success": False,
                "error": "Telegram Bot Token or Chat ID is missing. Configure in settings."
            }

        return await asyncio.to_thread(self._send_telegram_sync, message, token, cid)

    def _test_telegram_sync(self, bot_token: str, chat_id: str) -> Dict[str, Any]:
        try:
            # 1. Check getMe
            get_me_res = requests.get(f"https://api.telegram.org/bot{bot_token}/getMe", timeout=8)
            get_me = get_me_res.json()
            if not get_me.get("ok"):
                return {"success": False, "error": f"Invalid Bot Token: {get_me.get('description')}"}

            bot_name = get_me.get("result", {}).get("username", "UnknownBot")

            # 2. Send test message
            test_msg = f"<b>Bitcos AI Bot Connected!</b>\n\nMobile alerts are active for chat <code>{chat_id}</code>."
            send_res = requests.post(
                f"https://api.telegram.org/bot{bot_token}/sendMessage",
                json={"chat_id": chat_id, "text": test_msg, "parse_mode": "HTML"},
                timeout=8
            )
            send_data = send_res.json()
            if send_data.get("ok"):
                return {
                    "success": True,
                    "bot_username": bot_name,
                    "message": f"Successfully connected to @{bot_name} and sent test alert!"
                }
            else:
                return {
                    "success": False,
                    "bot_username": bot_name,
                    "error": f"Bot found (@{bot_name}), but failed to message Chat ID: {send_data.get('description')}. Make sure you typed /start in the bot!"
                }
        except Exception as e:
            return {"success": False, "error": str(e)}

    async def test_telegram_connection(self, bot_token: str, chat_id: str) -> Dict[str, Any]:
        """
        Test endpoint to verify Telegram credentials and get bot username.
        """
        return await asyncio.to_thread(self._test_telegram_sync, bot_token, chat_id)

    # --- BROADCAST MULTI-CHANNEL ALERT ---
    async def broadcast_alert(
        self,
        title: str,
        message: str,
        alert_type: str = "INFO",  # SETUP, PROFIT, RISK_WARNING, CRITICAL, INFO
        recipient_email: Optional[str] = None,
        telegram_token: Optional[str] = None,
        telegram_chat_id: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Sends the alert across Email and Telegram simultaneously and logs it in the live feed.
        """
        timestamp = datetime.utcnow().isoformat()
        results = {"email": None, "telegram": None}

        # 1. Format Telegram Message
        emoji_map = {
            "SETUP": "🎯",
            "PROFIT": "💰",
            "RISK_WARNING": "⚠️",
            "CRITICAL": "🚨",
            "INFO": "ℹ️"
        }
        emoji = emoji_map.get(alert_type.upper(), "📢")
        tg_text = f"<b>{emoji} BITCOS AI ALERT: {title}</b>\n\n{message}\n\n<i>Time: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}</i>"

        # 2. Dispatch in parallel
        tasks = []
        tasks.append(self.send_email(subject=title, body_text=message, recipient=recipient_email))
        tasks.append(self.send_telegram(message=tg_text, bot_token=telegram_token, chat_id=telegram_chat_id))

        res_email, res_tg = await asyncio.gather(*tasks, return_exceptions=True)

        results["email"] = res_email if isinstance(res_email, dict) else {"success": False, "error": str(res_email)}
        results["telegram"] = res_tg if isinstance(res_tg, dict) else {"success": False, "error": str(res_tg)}

        # 3. Record in Alert History
        alert_record = {
            "id": f"alert-{int(datetime.utcnow().timestamp() * 1000)}",
            "timestamp": timestamp,
            "type": alert_type.upper(),
            "title": title,
            "message": message,
            "results": results,
            "metadata": metadata or {}
        }
        self._log_alert(alert_record)

        return alert_record


notification_service = NotificationService()
